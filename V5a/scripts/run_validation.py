#!/usr/bin/env python
"""Run deterministic V4 validation checks (MRAC step, matching, invariants).

These checks answer narrower questions than the scenario benchmark:

* are the reference model, projection bounds and plant invariants respected?
* does the run provide evidence of adaptation superiority over fixed gains?

The step harness uses the same controller and plant classes as the benchmark.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from iara_v4.analysis.plots import COLORS  # noqa: E402
from iara_v4.control.gain_scheduler import GainScheduler  # noqa: E402
from iara_v4.control.mrac import MRACConfig, MRACController  # noqa: E402
from iara_v4.dynamics.model import VehicleParameters, physical_checks  # noqa: E402
from iara_v4.experiments.reference import analyze_scheduler  # noqa: E402
from iara_v4.experiments.validation import step_response_validation  # noqa: E402


def _fmt(value, digits: int = 4) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (float, np.floating)):
        return f"{float(value):.{digits}g}"
    return str(value)


def _series(result) -> dict:
    return {
        "time": result.time.tolist(),
        "heading": result.heading.tolist(),
        "heading_reference": result.heading_reference.tolist(),
        "reference_model": result.reference_model.tolist(),
        "yaw_rate": result.yaw_rate.tolist(),
        "rudder": result.rudder.tolist(),
        "kr": result.kr.tolist(),
        "kx1": result.kx1.tolist(),
        "kx2": result.kx2.tolist(),
    }


def write_markdown(payload: dict, path: Path) -> None:
    step = payload["step_response"]
    lines: list[str] = []
    lines.append("# IARA V4 deterministic validation report\n")
    lines.append(
        "Generated by `scripts/run_validation.py`.  The step response is a "
        "model-level test: a constant heading reference is applied to the "
        "3-DOF plant with the same MRAC controller used by the benchmark.  It "
        "is not a physical experiment.\n"
    )
    lines.append("## 1. MRAC step response (initial gain at 10% of matching)\n")
    lines.append(
        "| Controller | Reference-model RMSE [rad] | Heading RMSE [rad] | "
        "Final error [rad] | mean |delta| [rad] | Initial Kr | Final Kr | "
        "Matching Kr | Final / matching | Kr moved toward matching | "
        "Saturated fraction |"
    )
    lines.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|")
    for key in ("adaptive", "fixed"):
        row = step[key]
        lines.append(
            f"| {key} | {_fmt(row['reference_model_rmse'])} | "
            f"{_fmt(row['heading_rmse'])} | {_fmt(row['final_heading_error'])} | "
            f"{_fmt(row['mean_abs_rudder'])} | {_fmt(row['initial_kr'])} | "
            f"{_fmt(row['final_kr'])} | {_fmt(row['matching_kr'])} | "
            f"{_fmt(row['kr_fraction_of_matching'])} | "
            f"{_fmt(row['kr_moved_toward_matching'])} | "
            f"{_fmt(row['saturated_fraction'])} |"
        )
    lines.append(
        f"\nRelative reference-model RMSE improvement of adaptation: "
        f"**{100.0 * step['relative_rmse_improvement']:.2f}%**.  "
        f"Numerical validation pass: **{_fmt(step['pass'])}**.  "
        f"Adaptation superiority demonstrated: "
        f"**{_fmt(step['adaptation_superiority_demonstrated'])}**.\n"
    )

    lines.append("## 2. Reference model and matching\n")
    check = payload["reference_model"]
    lines.append(
        f"- Hurwitz: {_fmt(check['hurwitz'])} "
        f"(max real eigenvalue {_fmt(check['max_real_eigenvalue_A'])})\n"
        f"- P positive definite: {_fmt(check['p_positive_definite'])} "
        f"(min eigenvalue {_fmt(check['p_min_eigenvalue'])})\n"
        f"- Lyapunov residual norm: {_fmt(check['lyapunov_residual_norm'])}\n"
    )
    lines.append("| Speed [m/s] | A residual | B residual | Exact matching |")
    lines.append("|---:|---:|---:|---|")
    for speed, row in payload["matching"]["matching"].items():
        lines.append(
            f"| {speed} | {_fmt(row['A_residual_norm'])} | "
            f"{_fmt(row['B_residual_norm'])} | {_fmt(row['matching_exact'])} |"
        )

    lines.append("\n## 3. Scheduler certificate\n")
    cqlf = payload["scheduler"]["cqlf"]
    lines.append(
        f"- Maximum spectral radius: {_fmt(payload['scheduler']['max_spectral_radius'])}\n"
        f"- Stability margin: {_fmt(payload['scheduler']['min_stability_margin'])}\n"
        f"- CQLF success: {_fmt(cqlf['success'])}\n"
        f"- CQLF residual: {_fmt(cqlf['residual'])}\n"
        f"- Min eigenvalue of P: {_fmt(cqlf['min_eigenvalue_P'])}\n"
        f"- Worst closed-loop margin: {_fmt(max(cqlf['margins']))}\n"
    )

    lines.append("## 4. Plant invariants\n")
    for key, value in payload["physical_checks"].items():
        lines.append(f"- {key}: {_fmt(value)}")

    lines.append(
        "\n## 5. Acceptance criteria\n\n"
        "The numerical `pass` gate covers finite signals, actuator limits and "
        "valid reference-model behavior.  Adaptation superiority is reported "
        "as a separate scientific gate and is not silently folded into the "
        "safety gate.  The CQLF and plant checks are also reported separately.\n"
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def plot_step(payload: dict, path: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    step = payload["step_response"]
    adaptive = payload["series"]["adaptive"]
    fixed = payload["series"]["fixed"]
    time = np.asarray(adaptive["time"])
    ref_model = np.asarray(adaptive["reference_model"])
    target = np.asarray(adaptive["heading_reference"])

    fig, axes = plt.subplots(2, 1, figsize=(8.0, 6.2), sharex=True)
    axes[0].plot(time, target, color="#555555", linestyle=":", label="command")
    axes[0].plot(time, ref_model, color="#222222", linewidth=1.6, label="reference model")
    axes[0].plot(
        time,
        adaptive["heading"],
        color=COLORS[1],
        label="MRAC adaptive",
    )
    axes[0].plot(
        time,
        fixed["heading"],
        color=COLORS[0],
        linestyle="--",
        label="fixed gain (10%)",
    )
    axes[0].set_ylabel("heading [rad]")
    axes[0].grid(alpha=0.25)
    axes[0].legend(fontsize=8)
    axes[0].set_title("Yaw step response from 10% of the matching gains")

    matching = step["matching_kr_at_0_15"]
    axes[1].plot(time, adaptive["kr"], color=COLORS[1], label="$\\hat K_r$ adaptive")
    axes[1].plot(time, fixed["kr"], color=COLORS[0], linestyle="--", label="$\\hat K_r$ fixed")
    axes[1].axhline(
        matching, color="#222222", linestyle=":", label="matching $K_r^*$"
    )
    axes[1].set_xlabel("time [s]")
    axes[1].set_ylabel("$K_r$")
    axes[1].grid(alpha=0.25)
    axes[1].legend(fontsize=8)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=200, facecolor="white")
    plt.close(fig)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-dir", default=str(ROOT / "experiments" / "validation")
    )
    args = parser.parse_args()
    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)

    vehicle = VehicleParameters()
    step = step_response_validation(vehicle)
    controller = MRACController(MRACConfig(omega_n=5.5, zeta=1.0), vehicle=vehicle)
    scheduler = analyze_scheduler(
        vehicle,
        GainScheduler.corrected(vehicle, omega_n=2.0, zeta=1.0),
        ts=0.05,
    )
    payload = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "step_response": {
            key: value
            for key, value in step.items()
            if key != "series"
        },
        "series": {
            "adaptive": _series(step["series"]["adaptive"]),
            "fixed": _series(step["series"]["fixed"]),
        },
        "reference_model": controller.reference.check(),
        "matching": controller.matching_report(),
        "scheduler": scheduler,
        "physical_checks": physical_checks(vehicle),
        "scope": (
            "Deterministic model-level validation.  Not a sea trial and not a "
            "physical validation of the IARA."
        ),
    }
    (out / "validation.json").write_text(
        json.dumps(payload, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    write_markdown(payload, out / "validation.md")
    plot_step(payload, out / "mrac_step_response.png")
    print(json.dumps(payload["step_response"], indent=2, ensure_ascii=False))
    print(f"wrote {out / 'validation.json'}")
    print(f"wrote {out / 'validation.md'}")
    print(f"wrote {out / 'mrac_step_response.png'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
