#!/usr/bin/env python
"""Reconstruct and audit the legacy MATLAB controller; write certificates.

The output separates three kinds of statement:

* algebraic reconstruction of what the script contains;
* numerical verification of the reconstructed models and gain schedules;
* explicit documentation discrepancies.

No result here is a physical validation of the IARA.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from iara_v4.analysis.plots import plot_gain_schedule  # noqa: E402
from iara_v4.control.gain_scheduler import GainScheduler  # noqa: E402
from iara_v4.control.mrac import MRACConfig, MRACController  # noqa: E402
from iara_v4.dynamics.model import VehicleParameters, physical_checks  # noqa: E402
from iara_v4.experiments.reference import (  # noqa: E402
    analyze_scheduler,
    audit_report,
)


def _fmt(value, digits: int = 4) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (int, np.integer)):
        return str(int(value))
    if isinstance(value, (float, np.floating)):
        return f"{float(value):.{digits}g}"
    return str(value)


def write_markdown(payload: dict, path: Path) -> None:
    audit = payload["audit"]
    lines: list[str] = []
    lines.append("# MATLAB controller reconstruction and numerical audit\n")
    lines.append(
        "This file is generated by `scripts/run_reference_audit.py`.  It "
        "reconstructs the continuous design and the hard-coded ARX branches in "
        "`projeto_barco.m`, identifies the branch-label shift, and computes "
        "numerical stability certificates for the corrected scheduler.  It is "
        "an audit of the supplied script, not a physical validation of the "
        "vessel.\n"
    )

    lines.append("## 1. Continuous local models\n")
    lines.append(
        "The script uses `a = 1.6 q`, `b = 0.2 q^2`, `K = 30/q^2` and "
        "`Td = (2.4/q sqrt(bK) - a)/(bK)`.  Consequently the closed-loop "
        "damping ratio is `1.2/q`, not the constant `1.2` claimed in the "
        "complement document.\n"
    )
    lines.append("| q | a | b | K | Td | omega_n | zeta | poles |")
    lines.append("|---:|---:|---:|---:|---:|---:|---:|---|")
    for m in audit["models"]:
        poles = ", ".join(
            f"{p[0]:.2f}{p[1]:+.2f}j" for p in m["poles"]
        )
        lines.append(
            f"| {_fmt(m['q'])} | {_fmt(m['a'])} | {_fmt(m['b'])} | "
            f"{_fmt(m['k'])} | {_fmt(m['td'])} | {_fmt(m['wn'])} | "
            f"{_fmt(m['zeta'])} | {poles} |"
        )

    lines.append("\n## 2. Branch-label mapping\n")
    lines.append(
        "The hard-coded coefficients are compared with the ZOH discretisation "
        "of each reconstructed model at `Ts = 1 s`.  The best match exposes a "
        "one-position label shift.\n"
    )
    lines.append(
        "| Branch label v | Best model q | Max abs coefficient error | "
        "Within 1e-3 |"
    )
    lines.append("|---:|---:|---:|---|")
    for row in audit["branch_mapping"]["branches"]:
        lines.append(
            f"| {_fmt(row['branch_speed'])} | {_fmt(row['best_model_q'])} | "
            f"{_fmt(row['max_abs_error'])} | {_fmt(row['within_tolerance'])} |"
        )

    lines.append("\n## 3. Temporal interpretations\n")
    lines.append(
        "The script calls `c2d(..., 1)` but applies the coefficients every "
        "`0.01 s`.  The three defensible readings are reported separately; "
        "they are not interchangeable.\n"
    )
    lines.append(
        "| Interpretation | Final value | Peak | Overshoot | Settling 2% [s] | "
        "RMS after 2 s |"
    )
    lines.append("|---|---:|---:|---:|---:|---:|")
    for row in audit["temporal_interpretations"]["rows"]:
        lines.append(
            f"| {row['interpretation']} | {_fmt(row['final_value'])} | "
            f"{_fmt(row['peak'])} | {_fmt(row['overshoot_fraction'])} | "
            f"{_fmt(row['settling_time_2pct'])} | {_fmt(row['rms_after_2s'])} |"
        )

    lines.append("\n## 4. Corrected scheduler certificate\n")
    lines.append(
        "The corrected scheduler uses `kp = omega_n^2/b(q)` and "
        "`kd = (2 zeta omega_n - a(q))/b(q)` with `omega_n = 2.0`, "
        "`zeta = 1.0`.  The discrete closed-loop yaw matrices are checked on a "
        "31-point speed grid at `Ts = 0.05 s`.  The common-Lyapunov result is a "
        "numerical least-squares certificate, not a formal SDP proof.\n"
    )
    lines.append(
        "| Schedule | max spectral radius | min stability margin | CQLF | "
        "min eig(P) | max margin |"
    )
    lines.append("|---|---:|---:|---|---:|---:|")
    for name, result in payload["scheduler"].items():
        cqlf = result["cqlf"]
        lines.append(
            f"| {name} | {_fmt(result['max_spectral_radius'])} | "
            f"{_fmt(result['min_stability_margin'])} | "
            f"{_fmt(cqlf['success'])} | {_fmt(cqlf['min_eigenvalue_P'])} | "
            f"{_fmt(max(cqlf['margins']))} |"
        )

    lines.append("\n## 5. Plant invariants\n")
    lines.append("| Check | Value |")
    lines.append("|---|---:|")
    for key, value in payload["physical_checks"].items():
        lines.append(f"| {key} | {_fmt(value)} |")

    lines.append("\n## 6. MRAC matching and Lyapunov checks\n")
    matching = payload["mrac_matching"]
    reference = matching["reference_model"]
    lines.append(
        f"Reference model: Hurwitz={_fmt(reference['hurwitz'])}, "
        f"P positive definite={_fmt(reference['p_positive_definite'])}, "
        f"min eig(P)={_fmt(reference['p_min_eigenvalue'])}, "
        f"Lyapunov residual={_fmt(reference['lyapunov_residual_norm'])}.\n"
    )
    lines.append("| Speed [m/s] | A residual | B residual | Exact matching |")
    lines.append("|---:|---:|---:|---|")
    for speed, row in matching["matching"].items():
        lines.append(
            f"| {speed} | {_fmt(row['A_residual_norm'])} | "
            f"{_fmt(row['B_residual_norm'])} | {_fmt(row['matching_exact'])} |"
        )

    lines.append("\n## 7. Documentation discrepancies\n")
    for key, text in audit["documentation_discrepancies"].items():
        lines.append(f"- **{key}**: {text}")

    lines.append(
        "\n## 8. Scope statement\n\n"
        "The numbers above are algebraic and numerical properties of the "
        "reconstructed models.  They do not identify the real IARA, do not "
        "constitute a sea trial, and do not validate the V4 plant parameters.  "
        "The branch-label shift and the `c2d` timing mismatch are defects of "
        "the legacy script that V4 does not reproduce operationally.\n"
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-dir", default=str(ROOT / "experiments" / "reference_audit")
    )
    args = parser.parse_args()
    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)

    vehicle = VehicleParameters()
    grid = np.linspace(0.1, 1.0, 31)
    schedulers = {
        "corrected": GainScheduler.corrected(vehicle, omega_n=2.0, zeta=1.0),
        "matlab_absolute": GainScheduler.matlab_absolute(),
        "matlab_constant_zeta": GainScheduler.matlab_constant_zeta(),
    }
    scheduler_results = {
        name: analyze_scheduler(vehicle, scheduler, ts=0.05, grid=grid)
        for name, scheduler in schedulers.items()
    }
    mrac = MRACController(MRACConfig(omega_n=5.5, zeta=1.0), vehicle=vehicle)
    audit = audit_report()
    branches = audit["branch_mapping"]["branches"]
    reference_check = mrac.reference.check()
    gates = {
        "scheduler_discrete_stable": bool(
            all(result["max_spectral_radius"] < 1.0 for result in scheduler_results.values())
        ),
        "cqlf_corrected_scheduler": bool(
            scheduler_results["corrected"]["cqlf"]["success"]
        ),
        "cqlf_all_schedulers": bool(
            all(result["cqlf"]["success"] for result in scheduler_results.values())
        ),
        "branch_shift_detected": bool(audit["branch_mapping"]["label_shift_detected"]),
        "all_branches_within_tolerance": bool(
            all(row["within_tolerance"] for row in branches)
        ),
        "three_temporal_readings": len(audit["temporal_interpretations"]["rows"]) == 3,
        "zeta_speed_dependent_verified": bool(audit["gates"]["zeta_speed_dependent_verified"]),
        "ts_mismatch_documented": "ts_mismatch" in audit["documentation_discrepancies"],
        "mrac_reference_hurwitz": bool(reference_check["hurwitz"]),
        "mrac_lyapunov_positive": bool(reference_check["p_positive_definite"]),
    }
    payload = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "audit": audit,
        "gates": gates,
        "physical_checks": physical_checks(vehicle),
        "scheduler": scheduler_results,
        "mrac_matching": mrac.matching_report(),
        "notes": [
            "Nominal plant parameters are modelling hypotheses, not identified IARA data.",
            "The CQLF result is a numerical least-squares certificate, not a formal SDP proof.",
            "No result in this file is a physical validation of the vessel.",
        ],
    }
    (out / "reference_audit.json").write_text(
        json.dumps(payload, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    write_markdown(payload, out / "reference_audit.md")
    plot_gain_schedule(out / "gain_schedule.png")
    print(json.dumps(payload["gates"], indent=2, ensure_ascii=False))
    print(f"wrote {out / 'reference_audit.json'}")
    print(f"wrote {out / 'reference_audit.md'}")
    print(f"wrote {out / 'gain_schedule.png'}")
    release_gates = {
        key: value
        for key, value in payload["gates"].items()
        if key != "cqlf_all_schedulers"
    }
    return 0 if all(release_gates.values()) else 1


if __name__ == "__main__":
    raise SystemExit(main())
